-- Run in Supabase SQL Editor for a NEW project.
-- This creates the columns used by ASF CRM.
create table if not exists public.leads (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    business_name text not null,
    category text default 'Other',
    contact_person text,
    phone text,
    email text,
    city text,
    source_url text,
    status text default 'New',
    priority text default 'Warm',
    consent_to_marketing boolean default false,
    next_follow_up date,
    notes text,
    service_interest text,
    budget text,
    project_timeline text,
    preferred_language text default 'English'
);

-- Enable RLS. For a private single-user CRM using a server-side secret,
-- configure appropriate policies before using a publishable/anon key.
alter table public.leads enable row level security;

